void VMC::leg_pos(double phi1, double phi4)
{
  if (five_link_)
  {
    // Standard five-bar: phi1 = thigh absolute angle, phi4 = drive-link absolute angle,
    // both measured in the VMC plane (+x = chassis forward, +y = down). theta = 0 at straight-down.
    double YD, YB, XD, XB, lBD, A0, B0, C0, phi2, XC, YC;
    YD = l4_ * sin(phi4);
    YB = l1_ * sin(phi1);
    XD = l5_ + l4_ * cos(phi4);
    XB = l1_ * cos(phi1);
    lBD = sqrt((XD - XB) * (XD - XB) + (YD - YB) * (YD - YB));
    A0 = 2 * l2_ * (XD - XB);
    B0 = 2 * l2_ * (YD - YB);
    C0 = l2_ * l2_ + lBD * lBD - l3_ * l3_;
    double disc = A0 * A0 + B0 * B0 - C0 * C0;
    if (disc < 0.0)
      disc = 0.0;  // closure barely lost (numeric / limit touch): clamp to nearest assembly
    phi2 = 2 * atan2((B0 + sqrt(disc)), (A0 + C0));
    XC = l1_ * cos(phi1) + l2_ * cos(phi2);
    YC = l1_ * sin(phi1) + l2_ * sin(phi2);
    pos_.L0 = sqrt((XC - l5_ / 2) * (XC - l5_ / 2) + YC * YC);
    pos_.theta = -atan2((XC - l5_ / 2), YC);
    return;
  }
  double a_tmp;
  double t4;
  /*     This function was generated by the Symbolic Math Toolbox version 9.2.
   */
  /*     15-Sep-2025 20:28:02 */
  t4 = phi1 + phi4;
  a_tmp = cos(phi1) * l1_ + cos(t4) * l2_;
  t4 = sin(phi1) * l1_ + sin(t4) * l2_;
  pos_.L0 = sqrt(a_tmp * a_tmp + t4 * t4);
  pos_.theta = atan2(t4, a_tmp);
}

void VMC::leg_spd(double dphi1, double dphi4)
{
  static double last_L0_spd = J_[0][0] * dphi1 + J_[0][1] * dphi4;
  static double last_theta_spd = J_[1][0] * dphi1 + J_[1][1] * dphi4;

  // 速度映射
  spd_.dL0 = J_[0][0] * dphi1 + J_[0][1] * dphi4;     // dl0
  spd_.dTheta = J_[1][0] * dphi1 + J_[1][1] * dphi4;  // dphi0

  // leg_spd lp filter
  spd_.dL0 = 0.4 * spd_.dL0 + 0.6 * last_L0_spd;
  last_L0_spd = spd_.dL0;
  spd_.dTheta = 0.4 * spd_.dTheta + 0.6 * last_theta_spd;
  last_theta_spd = spd_.dTheta;
}

void VMC::leg_conv(double F, double Tp, double* T)
{
  // J^T * [F; Tp]
  T[0] = J_[0][0] * F + J_[1][0] * Tp;
  T[1] = J_[0][1] * F + J_[1][1] * Tp;
}

void VMC::calc_jacobian(double phi1, double phi4)
{
  phi1_ = phi1;
  phi4_ = phi4;
  if (five_link_)
  {
    // five-link jacobian (motor angles -> polar foot velocity)
    double YD, YB, XD, XB, lBD, A0, B0, C0, XC, YC;
    double phi2, phi3;
    double L0, phi0;
    double j11, j12, j21, j22;

    YD = l4_ * sin(phi4);
    YB = l1_ * sin(phi1);
    XD = l5_ + l4_ * cos(phi4);
    XB = l1_ * cos(phi1);
    lBD = sqrt((XD - XB) * (XD - XB) + (YD - YB) * (YD - YB));
    A0 = 2 * l2_ * (XD - XB);
    B0 = 2 * l2_ * (YD - YB);
    C0 = l2_ * l2_ + lBD * lBD - l3_ * l3_;
    double disc = A0 * A0 + B0 * B0 - C0 * C0;
    if (disc < 0.0)
      disc = 0.0;
    phi2 = 2 * atan2((B0 + sqrt(disc)), A0 + C0);
    phi3 = atan2(YB - YD + l2_ * sin(phi2), XB - XD + l2_ * cos(phi2));
    XC = l1_ * cos(phi1) + l2_ * cos(phi2);
    YC = l1_ * sin(phi1) + l2_ * sin(phi2);
    L0 = sqrt((XC - l5_ / 2) * (XC - l5_ / 2) + YC * YC);
    phi0 = atan2(YC, XC - l5_ / 2);

    double denom = sin(phi3 - phi2);
    if (fabs(denom) < 1e-4)
      denom = (denom < 0.0 ? -1e-4 : 1e-4);  // stay off the transmission singularity

    j11 = (l1_ * sin(phi0 - phi3) * sin(phi1 - phi2)) / denom;
    j12 = (l4_ * sin(phi0 - phi2) * sin(phi3 - phi4)) / denom;
    j21 = (l1_ * cos(phi0 - phi3) * sin(phi1 - phi2)) / (L0 * denom);
    j22 = (l4_ * cos(phi0 - phi2) * sin(phi3 - phi4)) / (L0 * denom);

    J_[0][0] = j11;
    J_[0][1] = j12;
    J_[1][0] = j21;
    J_[1][1] = j22;
    return;
  }
  // serial (gazebo)
  double phi2 = phi1 + phi4;

  double c1 = cos(phi1);
  double s1 = sin(phi1);
  double c2 = cos(phi2);
  double s2 = sin(phi2);

  // 末端笛卡尔坐标
  double Cx = l1_ * c1 + l2_ * c2;
  double Cy = l1_ * s1 + l2_ * s2;

  double L0 = sqrt(Cx * Cx + Cy * Cy);

  // 防止奇异
  if (L0 < 1e-8)
  {
    J_[0][0] = J_[0][1] = 0.0;
    J_[1][0] = J_[1][1] = 0.0;
    return;
  }

  // 偏导
  double dx_dphi1 = -l1_ * s1 - l2_ * s2;
  double dy_dphi1 = l1_ * c1 + l2_ * c2;

  double dx_dphi4 = -l2_ * s2;
  double dy_dphi4 = l2_ * c2;

  double inv_L0 = 1.0 / L0;
  double inv_L0_sq = 1.0 / (L0 * L0);

  // 第一行：dl0/dphi
  J_[0][0] = (Cx * dx_dphi1 + Cy * dy_dphi1) * inv_L0;
  J_[0][1] = (Cx * dx_dphi4 + Cy * dy_dphi4) * inv_L0;

  // 第二行：dphi0/dphi
  J_[1][0] = (Cx * dy_dphi1 - Cy * dx_dphi1) * inv_L0_sq;
  J_[1][1] = (Cx * dy_dphi4 - Cy * dx_dphi4) * inv_L0_sq;

  // five link vmc
  //  double YD, YB, XD, XB, lBD, A0, B0, C0, XC, YC;
  //  double phi2, phi3;
  //  double L0, phi0;
  //  double j11, j12, j21, j22;
  //
  //  YD = l4_ * sin(phi4);
  //  YB = l1_ * sin(phi1);
  //  XD = l5_ + l4_ * cos(phi4);
  //  XB = l1_ * cos(phi1);
  //  lBD = sqrt((XD - XB) * (XD - XB) + (YD - YB) * (YD - YB));
  //  A0 = 2 * l2_ * (XD - XB);
  //  B0 = 2 * l2_ * (YD - YB);
  //  C0 = l2_ * l2_ + lBD * lBD - l3_ * l3_;
  //  phi2 = 2 * atan2((B0 + sqrt(A0 * A0 + B0 * B0 - C0 * C0)), A0 + C0);
  //  phi3 = atan2(YB - YD + l2_ * sin(phi2), XB - XD + l2_ * cos(phi2));
  //  XC = l1_ * cos(phi1) + l2_ * cos(phi2);
  //  YC = l1_ * sin(phi1) + l2_ * sin(phi2);
  //  L0 = sqrt((XC - l5_ / 2) * (XC - l5_ / 2) + YC * YC);
  //  phi0 = atan2(YC, XC - l5_ / 2);
  //
  //  j11 = (l1_ * sin(phi0 - phi3) * sin(phi1 - phi2)) / sin(phi3 - phi2);
  //  j12 = (l4_ * sin(phi0 - phi2) * sin(phi3 - phi4)) / sin(phi3 - phi2);
  //  j21 = (l1_ * cos(phi0 - phi3) * sin(phi1 - phi2)) / (L0 * sin(phi3 - phi2));
  //  j22 = (l4_ * cos(phi0 - phi2) * sin(phi3 - phi4)) / (L0 * sin(phi3 - phi2));
  //
  //  J_[0][0] = j11;
  //  J_[0][1] = j12;
  //  J_[1][0] = j21;
  //  J_[1][1] = j22;
}

